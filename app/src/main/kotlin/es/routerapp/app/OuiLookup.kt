package es.routerapp.app

/**
 * Resolved hardware vendor or privacy status for a MAC address.
 */
data class MacVendorInfo(
    val vendor: String? = null,
    val isPrivate: Boolean = false,
) {
    val displayVendor: String?
        get() = if (isPrivate) null else vendor
}

/**
 * Offline IEEE Organizationally Unique Identifier (OUI) lookup utility and
 * IEEE 802 locally administered / randomized MAC address detector.
 */
object OuiLookup {

    /**
     * Checks if the MAC address has the IEEE 802 locally administered bit set (bit 1 of octet 0).
     * If true, this indicates a randomized or private MAC address (e.g. Android / iOS Private Wi-Fi).
     */
    fun isLocallyAdministered(mac: String): Boolean {
        val clean = mac.filter { it.isLetterOrDigit() }
        if (clean.length < 2) return false
        val firstByte = clean.substring(0, 2).toIntOrNull(16) ?: return false
        return (firstByte and 0x02) != 0
    }

    /**
     * Resolves the hardware vendor or private status from the given MAC address.
     */
    fun resolve(mac: String): MacVendorInfo {
        if (isLocallyAdministered(mac)) {
            return MacVendorInfo(vendor = null, isPrivate = true)
        }
        val clean = mac.filter { it.isLetterOrDigit() }.uppercase()
        if (clean.length < 6) {
            return MacVendorInfo(vendor = null, isPrivate = false)
        }
        val oui = clean.substring(0, 6)
        val vendor = OUI_DATABASE[oui]
        return MacVendorInfo(vendor = vendor, isPrivate = false)
    }

    /**
     * Returns the vendor name if known and not private, or null.
     */
    fun getVendor(mac: String): String? = resolve(mac).vendor

